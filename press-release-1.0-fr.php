<h1>Instantbird 1.0 - Communiqué de presse</h1>

<p>LILLE, FRANCE - 28 juin 2011 - L'équipe d'Instantbird est ravie et fière de vous annoncer la sortie aujourd'hui de sa version la plus élaborée&nbsp;: <strong>Instantbird 1.0</strong> est disponible en 11 langues !</p>
<p>Instantbird est un client de <strong>messagerie instantanée</strong> qui respecte ses utilisateurs : il est très simple à prendre en main et largement <strong>personnalisable&nbsp;!</strong></p>
</p>

<p>Conçu avec la richesse de l'expérience acquise des logiciels <strong>open-source</strong>, Instantbird est à même de tirer parti de la puissance de Pidgin (via sa bibliothèque libpurple) et de la technologie de Mozilla Firefox, ce qui lui permet de vous donner accès à un large éventail de réseaux de messagerie instantanée, tout en s'appuyant sur une plateforme extensible bien connue. Bien qu'Instantbird soit déjà <strong>complètement multi-plateforme</strong> (fonctionne sous Windows, Mac OS X et Linux), nous faisons de notre mieux pour que l'aspect de l'interface soit familier et que son ergonomie rende Instantbird <strong>accessible et agréable à tous</strong>.</p>


<p><img src="press/screenshots/1.0-winaero-screenshot-homepage-big-fr.png" alt="Capture d'écran d'Instantbird 1.0 sous Windows 7"/></p>

<h2>Réseaux pris en charge</h2>

<p>D'abord et avant tout, Instantbird est un client de messagerie instantanée qui fonctionne sur toute une gamme de réseaux, en particulier&nbsp;:</p>
<ul>
<li>AOL Instant Messenger (AIM)</li>
<li>Facebook Chat</li>
<li>Google Talk</li>
<li>Twitter</li>
<li>Windows Live Messenger (MSN Messenger)</li>
<li>XMPP (Jabber)</li>
<li>Yahoo! Messenger</li>

</ul>
<p>…mais beaucoup d'autres encore, tels que&nbsp;: Gadu-Gadu, Novell Groupwise, ICQ, IRC, MySpaceIM, Netsoul, QQ, SIMPLE, Yahoo! JAPAN, et vous en trouverez encore d'autres disponibles sur le <a href="https://addons.instantbird.org/en-US/instantbird/">Site Web des modules complémentaires pour Instantbird</a>,
comme <a href="https://addons.instantbird.org/en-US/instantbird/addon/269">Omegle</a> et
<a href="https://addons.instantbird.org/en-US/instantbird/addon/255">LJ Talk (LiveJournal)</a>.</p>

<h2>Personnalisation</h2>
<p>Nous pensons que l'utilisateur doit pouvoir <strong>personnaliser</strong> à son gré son client de messagerie instantanée&nbsp;: et selon nous le meilleur moyen de donner le pouvoir à l'utilisateur est une interface <strong>simple et efficace</strong>, sans chercher à le noyer sous des centaines d'options. Nous lui offrons sur un plateau l'extraordinaire potentiel d'extensibilité des applications Mozilla. Tous les éléments d'Instantbird sont personnalisables, depuis l'aspect des messages jusqu'au thème d'Instantbird, en passant par l'interface utilisateur et les protocoles. Il existe déjà plus de 250 modules complémentaires disponibles, voici quelques-uns de nos favoris&nbsp;:</p>

<ul>
<li><a href="https://addons.instantbird.org/en-US/instantbird/addon/248">Colorize</a> -- modifiez la couleur attribuée au copain avec lequel vous parlez en privé, en fonction de son nom</li>
<li><a href="https://addons.instantbird.org/en-US/instantbird/addon/250">Highlight</a> -- soyez averti lorsque certains mots apparaissent dans un chat, comme s'il s'agissait de votre pseudo</li>
<li><a href="https://addons.instantbird.org/en-US/instantbird/addon/276">Tab Complete</a> -- complétion des pseudos et commandes avec la touche de tabulation</li>
<li><a href="https://addons.instantbird.org/en-US/instantbird/addon/249">Reply to Nick</a> -- réponse rapide facile&nbsp;: un double clic sur un message suffit à insérer le nom du destinataire dans la zone de saisie de vos messages</li>

<li><a href="https://addons.instantbird.org/en-US/instantbird/addon/251">Show Nick</a> -- colorie les pseudos dans les conversations à interlocuteurs multiples</li>
<li><a href="https://addons.instantbird.org/en-US/instantbird/addon/244">Vertical Tabs</a> -- trop de conversations ouvertes&nbsp;? Disposez vos onglets verticalement pour y voir clair&nbsp;!</li>
</ul>

<h2>Respect des utilisateurs</h2>
<p>Comme nous accordons une grande importance au <strong>respect de nos utilisateurs</strong>, nous leur offrons un produit <strong>gratuit et sans publicité</strong> respectant leur vie privée et qui ne collecte aucune donnée personnelle (Instantbird ne contacte nos serveurs que pour rechercher des mises à jour, ou dans le cas heureusement rare d'un plantage).</p>


<h2>Qui sommes-nous&nbsp;?</h2>
<p>L'équipe d'Instantbird est un groupe de bénévoles passionnés et déterminés à donner aux utilisateurs de messagerie instantanée un logiciel puissant, stable et sympathique. Pour en savoir plus, voyez <a href="http://instantbird.com/about.html">qui nous sommes</a> ainsi que <a href="http://instantbird.org/">nos principes et nos valeurs fondamentales</a>.</p>

<p>Instantbird a bénéficié de précieuses contributions de la communauté Mozilla au sens large, cependant il n'est financé en aucune façon par la fondation Mozilla. L'infrastructure de niveau professionnel utilisée pour créer et maintenir Instantbird a été financée par ses créateurs qui croient fermement en l'importance de ce projet. L'ampleur et la progression de la base d'utilisateurs nous incitent à penser que ce projet pourrait dégager des revenus tout en respectant l'utilisateur : Instantbird deviendrait économiquement rentable et permettrait à l'association d'engager des contributeurs-clés, selon le modèle employé par Mozilla pour Firefox.</p>

<h2>Merci d'avoir lu jusque-là&nbsp;!</h2>

<p>Merci de prendre quelques minutes pour jeter un coup d'œil sur Instantbird. Vous pouvez <a href="download-1.0.html">télécharger la version 1.0</a> et l'essayer. Si vous avez des questions ou si vous désirez davantage d'informations, merci de <a href="about.html">nous contacter</a>.</p>
<p>Si vous avez besoin du logo pour illustrer un billet sur Instantbird ou si vous manquez de temps pour faire une capture d'écran, nous mettons ces <a href="press-images-1.0.html">images</a> à votre disposition.</p>
